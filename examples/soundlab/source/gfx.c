static const glyph_t *find(char c)
{
    c = (char)toupper((unsigned char)c);
    for (unsigned i = 0; i < sizeof(font) / sizeof(font[0]); i++)
        if (font[i].ch == c) return &font[i];
    return NULL;
}

int gfx_text_width(const char *s, int scale) { return (int)strlen(s) * 6 * scale; }

void gfx_text(int x, int y, const char *s, u32 c, int scale)
{
    for (; *s; s++, x += 6 * scale) {
        const glyph_t *g = find(*s);
        if (!g) continue;                                   // blank
        for (int r = 0; r < 7; r++)
            for (int k = 0; k < 5; k++)
                if (g->rows[r][k] == '#')
                    gfx_rect(x + k * scale, y + r * scale, scale, scale, c);
    }
}
