// Top screen drawing, rotated framebuffer.
#include <string.h>
#include <ctype.h>
#include "gfx.h"

static u8 *fb;

void gfx_begin(u32 bg)
{
    fb = gfxGetFramebuffer(GFX_TOP, GFX_LEFT, NULL, NULL);
    u8 b = bg & 0xFF, g = (bg >> 8) & 0xFF, r = (bg >> 16) & 0xFF;
    for (int i = 0; i < 400 * 240; i++) { fb[3 * i] = b; fb[3 * i + 1] = g; fb[3 * i + 2] = r; }
}

static inline void px(int x, int y, u32 c)
{
    if ((unsigned)x >= 400 || (unsigned)y >= 240) return;
    u8 *p = fb + 3 * (x * 240 + (239 - y));
    p[0] = c & 0xFF; p[1] = (c >> 8) & 0xFF; p[2] = (c >> 16) & 0xFF;
}

void gfx_rect(int x, int y, int w, int h, u32 c)
{
    for (int i = 0; i < w; i++) for (int j = 0; j < h; j++) px(x + i, y + j, c);
}
void gfx_hline(int x, int y, int w, u32 c) { for (int i = 0; i < w; i++) px(x + i, y, c); }
void gfx_vline(int x, int y, int h, u32 c) { for (int j = 0; j < h; j++) px(x, y + j, c); }

void gfx_line(int x0, int y0, int x1, int y1, u32 c)
{
    int dx = x1 > x0 ? x1 - x0 : x0 - x1, sx = x0 < x1 ? 1 : -1;
    int dy = y1 > y0 ? y0 - y1 : y1 - y0, sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (;;) {
        px(x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

