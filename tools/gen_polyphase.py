"""Write the 4-tap polyphase interpolation table (Kaiser-windowed sinc, Q14)."""
import math
import sys

PHASES = 128
CUTOFF = 0.85
BETA = 3.0


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while term > 1e-12 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def kaiser(x):
    return bessel_i0(BETA * math.sqrt(max(0.0, 1 - x * x))) / bessel_i0(BETA)


def sinc(x):
    return 1.0 if abs(x) < 1e-12 else math.sin(math.pi * x) / (math.pi * x)


def rows():
    for p in range(PHASES):
        mu = p / PHASES
        taps = [CUTOFF * sinc(CUTOFF * d) * kaiser(d / 2.0) for d in (-1 - mu, -mu, 1 - mu, 2 - mu)]
        total = sum(taps)
        q = [int(round(t / total * 16384)) for t in taps]
        q[1] += 16384 - sum(q)          # unity DC gain after rounding
        yield q


def main():
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write("// SPDX-License-Identifier: BSD-2-Clause\n")
        f.write("// Generated by tools/gen_polyphase.py\n")
        f.write("#pragma once\n")
        f.write("static const s16 polyphase_table[%d * 4] YMEM_RO = {\n" % PHASES)
        for q in rows():
            f.write("    %d, %d, %d, %d,\n" % tuple(q))
        f.write("};\n")


if __name__ == "__main__":
    main()
